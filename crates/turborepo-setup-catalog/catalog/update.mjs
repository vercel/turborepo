#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import {
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const AQUA_REGISTRY = "aquaproj/aqua-registry";
const MISE = "https://github.com/jdx/mise";

const BUILT_IN = new Set(
  "bun go javascript node npm pnpm python rust rustup turbo uv yarn".split(" ")
);

const OVERRIDES = {
  // mise installs Zig through its own adapter. The aqua recipe covers the same releases.
  zig: "ziglang/zig"
};

const catalog = dirname(fileURLToPath(import.meta.url));

async function fetchOk(url) {
  const response = await fetch(url, {
    headers: { "user-agent": "turborepo-catalog-update" }
  });
  if (!response.ok) {
    throw new Error(`${url}: HTTP ${response.status}`);
  }
  return response;
}

async function aquaTag(requested) {
  if (requested) {
    return requested;
  }
  const latest = await fetchOk(
    `https://api.github.com/repos/${AQUA_REGISTRY}/releases/latest`
  );
  return (await latest.json()).tag_name;
}

function git(cwd, ...args) {
  return execFileSync("git", args, { cwd, encoding: "utf8" }).trim();
}

function checkoutMiseRegistry(directory, commit) {
  git(directory, "init", "--quiet");
  git(directory, "remote", "add", "origin", MISE);
  git(directory, "sparse-checkout", "set", "registry");
  git(
    directory,
    "fetch",
    "--quiet",
    "--depth",
    "1",
    "--filter=blob:none",
    "origin",
    commit ?? "HEAD"
  );
  git(directory, "checkout", "--quiet", "FETCH_HEAD");
  return git(directory, "rev-parse", "HEAD");
}

function identifier(name) {
  return /^[a-z][a-z0-9_-]{0,63}$/.test(name) && !BUILT_IN.has(name);
}

// mise lists a tool's sources in preference order. Only aqua recipes are
// usable here, so a name maps to the first aqua source mise lists for it.
function parseTool(text) {
  const backends =
    /^backends\s*=\s*\[(.*?)^\]/ms.exec(text)?.[1] ??
    /^backends\s*=\s*\[(.*?)\]/m.exec(text)?.[1] ??
    "";
  const aliases = /^aliases\s*=\s*\[(.*?)\]/ms.exec(text)?.[1] ?? "";
  return {
    aqua: /"aqua:([^"[]+)/.exec(backends)?.[1],
    aliases: [...aliases.matchAll(/"([^"]+)"/g)].map((match) => match[1])
  };
}

function shortNames(registry) {
  const tools = readdirSync(registry)
    .filter((file) => file.endsWith(".toml"))
    .map((file) => ({
      name: file.slice(0, -".toml".length),
      ...parseTool(readFileSync(join(registry, file), "utf8"))
    }))
    .filter((tool) => tool.aqua);
  const names = new Map();
  for (const tool of tools) {
    if (identifier(tool.name)) {
      names.set(tool.name, tool.aqua);
    }
  }
  for (const tool of tools) {
    for (const alias of tool.aliases) {
      if (identifier(alias) && !names.has(alias)) {
        names.set(alias, tool.aqua);
      }
    }
  }
  for (const [name, id] of Object.entries(OVERRIDES)) {
    names.set(name, id);
  }
  return [...names].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

const tag = await aquaTag(process.argv[2]);
const recipes = await fetchOk(
  `https://raw.githubusercontent.com/${AQUA_REGISTRY}/${tag}/registry.yaml`
);
writeFileSync(
  join(catalog, "aqua-registry.yaml.gz"),
  gzipSync(Buffer.from(await recipes.arrayBuffer()), { level: 9 })
);

const checkout = mkdtempSync(join(tmpdir(), "turborepo-catalog-"));
try {
  const commit = checkoutMiseRegistry(checkout, process.argv[3]);
  const names = shortNames(join(checkout, "registry"));
  const header = [
    "# Short tool names for `setup.additionalTools`, mapped to aqua package IDs.",
    "# Generated by update.mjs. Do not edit: add a name to OVERRIDES there instead.",
    `# aqua-registry ${tag}`,
    `# mise ${commit}`
  ];
  const rows = names.map(([name, id]) => `${name}\t${id}`);
  writeFileSync(
    join(catalog, "names.tsv"),
    `${[...header, ...rows].join("\n")}\n`
  );
  console.log(`aqua-registry ${tag}, mise ${commit}: ${names.length} names`);
} finally {
  rmSync(checkout, { recursive: true, force: true });
}
