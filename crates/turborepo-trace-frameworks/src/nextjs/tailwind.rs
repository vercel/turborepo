//! Tailwind CSS: which files the generated stylesheet depends on, and the
//! class-token heuristic.
//!
//! Tailwind scans source files for class candidates and generates one
//! stylesheet. The **strict** model ([`TailwindMode::Strict`], the default) is
//! therefore: every scanned file is an input of the stylesheet, and the
//! stylesheet is a global input of every route. On a real app that collapses
//! selection to "run everything" for most UI commits.
//!
//! The **token** heuristic ([`TailwindMode::Tokens`], opt-in) says a changed
//! file affects the stylesheet only if its set of class-candidate tokens
//! changed ([`token_diff`]); and if the caller provides the tokens of every
//! other scanned file, only if the change adds a token no other file has or
//! removes the last occurrence of one ([`css_affected`]).
//!
//! **Soundness caveat:** class names built dynamically (`` `text-${color}-500`
//! ``, lookups in data files that are not scanned, `@apply` of utilities
//! defined elsewhere, or a safelist) are invisible to token extraction, and so
//! is a change in a token's *meaning* (a `@theme` or config edit; those files
//! are global inputs anyway). Tokens are extracted the way Tailwind's scanner
//! does it, over-approximately (any run of class-candidate characters), so the
//! heuristic errs towards "changed".

use std::{
    collections::BTreeSet,
    path::{Path, PathBuf},
};

use serde::Serialize;

use crate::fsx::PathFsx;

/// How CSS generated by Tailwind is modelled.
#[derive(Copy, Clone, Debug, Default, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum TailwindMode {
    /// Every scanned file is an input of the global stylesheet (sound,
    /// default).
    #[default]
    Strict,
    /// A changed scanned file affects the stylesheet only if its set of
    /// utility-shaped class tokens changed.
    Tokens,
    /// The research model: only the CSS entry files and the config are global;
    /// a class token only styles elements rendered from files that contain
    /// it, and those files are already in the closure of the routes that
    /// render them. A changed scanned file never affects the stylesheet
    /// globally.
    Closure,
}

/// What was found about Tailwind in an app.
#[derive(Clone, Debug, Default, Serialize)]
pub struct TailwindInfo {
    /// Tailwind is used.
    pub enabled: bool,
    /// CSS entry files (with `@import "tailwindcss"`, `@tailwind`, `@source`,
    /// `@theme`).
    pub css_files: Vec<PathBuf>,
    /// `tailwind.config.*` files.
    pub config_files: Vec<PathBuf>,
    /// Scanned source directories (absolute) with their globs; `**` when
    /// automatic.
    pub sources: Vec<(PathBuf, String)>,
    /// `@source not` / excluded directories.
    pub excluded: Vec<PathBuf>,
    /// Names of `@utility` rules in the CSS entries.
    pub custom_utilities: Vec<String>,
}

/// Config names.
pub const CONFIG_NAMES: &[&str] = &[
    "tailwind.config.js",
    "tailwind.config.cjs",
    "tailwind.config.mjs",
    "tailwind.config.ts",
    "tailwind.config.mts",
];

fn quoted_args(line: &str) -> Vec<String> {
    let mut out = Vec::new();
    let b = line.as_bytes();
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'"' || b[i] == b'\'' {
            let q = b[i];
            let s = i + 1;
            i += 1;
            while i < b.len() && b[i] != q {
                i += 1;
            }
            out.push(line[s..i.min(line.len())].to_string());
        }
        i += 1;
    }
    out
}

impl TailwindInfo {
    /// Detects Tailwind for the app at `root`, given the CSS files to inspect
    /// (for example every `.css` file under the app directory).
    pub fn detect(root: &Path, css_candidates: &[PathBuf]) -> TailwindInfo {
        let mut t = TailwindInfo::default();
        for n in CONFIG_NAMES {
            let p = root.join(n);
            if p.fx_is_file() {
                t.config_files.push(p);
            }
        }
        let mut auto = false;
        for css in css_candidates {
            let Ok(text) = crate::fsx::read_to_string(css) else {
                continue;
            };
            let dir = css.parent().unwrap_or(root);
            let mut is_entry = false;
            for line in text.lines() {
                let l = line.trim();
                if l.starts_with("@import")
                    && (l.contains("\"tailwindcss") || l.contains("'tailwindcss"))
                {
                    is_entry = true;
                    if !l.contains("source(none)") {
                        auto = true;
                    }
                    if let Some(p) = l.split("source(").nth(1) {
                        for a in quoted_args(p) {
                            t.sources.push((crate::fsx::join(dir, &a), "**".into()));
                        }
                    }
                } else if l.starts_with("@tailwind")
                    || l.starts_with("@theme")
                    || l.starts_with("@config")
                    || l.starts_with("@plugin")
                {
                    is_entry = true;
                    if l.starts_with("@tailwind") && t.config_files.is_empty() {
                        auto = true;
                    }
                } else if let Some(rest) = l.strip_prefix("@utility") {
                    let name = rest
                        .trim()
                        .trim_end_matches('{')
                        .trim()
                        .trim_end_matches("-*");
                    if !name.is_empty() {
                        t.custom_utilities.push(name.to_string());
                    }
                } else if let Some(rest) = l.strip_prefix("@source") {
                    is_entry = true;
                    let rest = rest.trim();
                    let (not, rest) = match rest.strip_prefix("not") {
                        Some(r) => (true, r),
                        None => (false, rest),
                    };
                    for a in quoted_args(rest) {
                        let (base, glob) = split_glob(&a);
                        let p = crate::fsx::join(dir, base);
                        if not {
                            t.excluded.push(p);
                        } else {
                            t.sources.push((p, glob));
                        }
                    }
                }
            }
            if is_entry {
                t.css_files.push(css.clone());
            }
        }
        if !t.config_files.is_empty() {
            // v3: `content` globs from the config; read them statically where possible.
            for c in &t.config_files {
                let l = crate::jsconfig::load(c, crate::jsconfig::LoadOptions::default());
                let mut got = false;
                if let Some(v) = l.value.as_ref().and_then(|v| v.field("content")) {
                    let arr = match &v {
                        turborepo_trace_lang_js::extract::config::ConfigVal::Obj(_) => {
                            v.field("files")
                        }
                        _ => Some(v.clone()),
                    };
                    if let Some(turborepo_trace_lang_js::extract::config::ConfigVal::Arr(xs)) = arr
                    {
                        for x in xs {
                            if let Some(s) = x.as_str() {
                                let (base, glob) = split_glob(s);
                                t.sources.push((
                                    crate::fsx::join(c.parent().unwrap_or(root), base),
                                    glob,
                                ));
                                got = true;
                            }
                        }
                    }
                }
                if !got {
                    auto = true;
                }
            }
        }
        if auto {
            t.sources.push((root.to_path_buf(), "**".into()));
        }
        t.enabled = !t.css_files.is_empty() || !t.config_files.is_empty();
        if !t.enabled {
            t.sources.clear();
        }
        t.sources.sort();
        t.sources.dedup();
        t
    }

    /// Whether `file` (absolute) is scanned for class names.
    pub fn scans(&self, file: &Path) -> bool {
        if !self.enabled || self.excluded.iter().any(|e| file.starts_with(e)) {
            return false;
        }
        // By the path below the repository root: the checkout may live below a
        // directory of one of these names.
        if crate::fsx::local(file).components().any(|c| {
            matches!(
                c.as_os_str().to_str(),
                Some("node_modules" | ".next" | ".git")
            )
        }) {
            return false;
        }
        let ext = file.extension().and_then(|e| e.to_str()).unwrap_or("");
        if matches!(
            ext,
            "css" | "png" | "jpg" | "jpeg" | "gif" | "ico" | "woff" | "woff2" | "lock"
        ) {
            return false;
        }
        self.sources.iter().any(|(dir, glob)| {
            file.strip_prefix(dir).is_ok_and(|rel| {
                glob == "**" || crate::pattern::glob_matches(glob, &rel.to_string_lossy())
            })
        })
    }
}

fn split_glob(s: &str) -> (&str, String) {
    let meta = s.find(['*', '{', '?', '[']).unwrap_or(s.len());
    let base_end = s[..meta].rfind('/').unwrap_or(0);
    if meta == s.len() {
        return (s, "**".into());
    }
    (
        &s[..base_end],
        s[base_end..].trim_start_matches('/').to_string(),
    )
}

fn is_candidate_byte(b: u8) -> bool {
    b.is_ascii_alphanumeric()
        || matches!(
            b,
            b'-' | b'_'
                | b':'
                | b'/'
                | b'.'
                | b'['
                | b']'
                | b'#'
                | b'%'
                | b'!'
                | b'@'
                | b'('
                | b')'
                | b','
                | b'&'
                | b'='
                | b'*'
                | b'>'
                | b'+'
                | b'~'
        )
}

/// Class-candidate tokens of a source file, as Tailwind's scanner sees them:
/// maximal runs of candidate characters, split at whitespace and quotes, that
/// contain a letter. Over-approximate on purpose (it also yields identifiers
/// and words).
pub fn class_tokens(src: &[u8]) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    let mut i = 0;
    while i < src.len() {
        if !is_candidate_byte(src[i]) {
            i += 1;
            continue;
        }
        let s = i;
        while i < src.len() && is_candidate_byte(src[i]) {
            i += 1;
        }
        let tok = &src[s..i];
        let trimmed = trim_token(tok);
        if trimmed.len() >= 2
            && trimmed.iter().any(|b| b.is_ascii_alphabetic())
            && let Ok(t) = std::str::from_utf8(trimmed)
        {
            out.insert(t.to_string());
        }
    }
    out
}

fn trim_token(t: &[u8]) -> &[u8] {
    let mut a = 0;
    let mut b = t.len();
    while a < b
        && matches!(
            t[a],
            b'.' | b',' | b'(' | b':' | b'=' | b'>' | b'+' | b'~' | b'&' | b'*'
        )
    {
        a += 1;
    }
    while b > a
        && matches!(
            t[b - 1],
            b'.' | b',' | b')' | b':' | b'=' | b'>' | b'+' | b'~' | b'&' | b'*'
        )
    {
        b -= 1;
    }
    &t[a..b]
}

/// Tokens added and removed between two versions of a file.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize)]
pub struct TokenDiff {
    /// Tokens only in the new version.
    pub added: BTreeSet<String>,
    /// Tokens only in the old version.
    pub removed: BTreeSet<String>,
}

impl TokenDiff {
    /// No token changed.
    pub fn is_empty(&self) -> bool {
        self.added.is_empty() && self.removed.is_empty()
    }
}

