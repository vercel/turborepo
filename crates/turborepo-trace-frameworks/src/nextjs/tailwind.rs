/// Whether a token can be a Tailwind class: an arbitrary property
/// (`[mask-type:luminance]`), or `[variant:]*[!][-]root[-value][/modifier][!]`
/// with a core or `custom` root.
pub fn looks_like_utility(tok: &str, custom: &[String]) -> bool {
    let mut depth = 0i32;
    let mut last = 0;
    for (i, c) in tok.char_indices() {
        match c {
            '[' | '(' => depth += 1,
            ']' | ')' => depth -= 1,
            ':' if depth == 0 => last = i + 1,
            _ => {}
        }
    }
    let base = tok[last..].trim_start_matches('!').trim_end_matches('!');
    let base = base.strip_prefix('-').unwrap_or(base);
    if base.starts_with('[') && base.ends_with(']') && base.contains(':') {
        return true;
    }
    if base.is_empty() || !base.as_bytes()[0].is_ascii_lowercase() {
        return false;
    }
    let root = base.split(['-', '/', '[']).next().unwrap_or(base);
    UTILITY_ROOTS.contains(&root)
        || custom
            .iter()
            .any(|c| base == c || base.starts_with(&format!("{c}-")))
}

/// The utility-token difference of `old` → `new` (`None` = the file did not
/// exist).
pub fn token_diff(old: Option<&[u8]>, new: Option<&[u8]>, custom: &[String]) -> TokenDiff {
    let f = |src: Option<&[u8]>| -> BTreeSet<String> {
        src.map(class_tokens)
            .unwrap_or_default()
            .into_iter()
            .filter(|t| looks_like_utility(t, custom))
            .collect()
    };
    let o = f(old);
    let n = f(new);
    TokenDiff {
        added: n.difference(&o).cloned().collect(),
        removed: o.difference(&n).cloned().collect(),
    }
}

/// Whether a change of one file changes the generated stylesheet under the
/// token heuristic: its utility-token set changed and, if `others` (tokens of
/// every other scanned file) is given, some added or removed token occurs in no
/// other file. `custom`: `@utility` names.
pub fn css_affected(
    old: Option<&[u8]>,
    new: Option<&[u8]>,
    others: Option<&BTreeSet<String>>,
    custom: &[String],
) -> bool {
    let d = token_diff(old, new, custom);
    match others {
        None => !d.is_empty(),
        Some(o) => d.added.iter().chain(&d.removed).any(|t| !o.contains(t)),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tokens() {
        let t = class_tokens(br#"<div className="p-4 md:flex hover:bg-[#fff] w-1/2">{x}</div>"#);
        for k in ["p-4", "md:flex", "hover:bg-[#fff]", "w-1/2"] {
            assert!(t.contains(k), "{k} in {t:?}");
        }
    }

    #[test]
    fn diff() {
        let a = br#"cn("p-4 text-sm")"#;
        let b = br#"cn("p-4 text-sm", isOpen && "flex")"#;
        let c = br#"cn( "text-sm  p-4" )"#;
        assert!(css_affected(Some(a), Some(b), None, &[]));
        assert!(!css_affected(Some(a), Some(c), None, &[]));
        let others: BTreeSet<String> = ["flex"].iter().map(|s| s.to_string()).collect();
        assert!(!css_affected(Some(a), Some(b), Some(&others), &[]));
        // Identifiers are not utilities.
        assert!(!css_affected(
            Some(b"const a = 1"),
            Some(b"const fooBar = 1"),
            None,
            &[]
        ));
        assert!(looks_like_utility("md:hover:bg-[#fff]/50", &[]));
        assert!(looks_like_utility("-mt-2", &[]));
        assert!(looks_like_utility("[mask-type:luminance]", &[]));
        assert!(looks_like_utility("btn-primary", &["btn".to_string()]));
        assert!(!looks_like_utility("useState", &[]));
    }
}
