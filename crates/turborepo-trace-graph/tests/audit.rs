//! The unlikely-path audit (`turborepo_trace_graph::audit`): signals and
//! attribution on small synthetic graphs.

// Test code: helpers outside `#[test]` functions unwrap and expect as the tests do.
#![allow(clippy::unwrap_used, clippy::expect_used)]

use turborepo_trace_graph::{
    AffectedOptions, ChangeKind, ChangeSet, EdgeFilter, EdgeSpec, Engine, GraphBuilder, GraphView,
    MemGraph, NodeId, NodeSet, PackageId, RefFlags, RefKind, UncertaintyKind, Verdict,
    audit::{
        AuditOptions, AuditReport, AuditSource, HUB_LANG, Signal, SourceKind, TASK_LANG,
        VerdictFilter,
    },
};

struct Fx {
    g: MemGraph,
    entries: Vec<NodeId>,
    deps: Option<Vec<Vec<PackageId>>>,
}

impl Fx {
    fn run(&self, cs: &ChangeSet) -> AuditReport {
        self.run_top(cs, 15)
    }

    fn run_top(&self, cs: &ChangeSet, top: usize) -> AuditReport {
        let e = Engine::new(&self.g);
        let entries = NodeSet::from_iter_in(self.g.node_count(), self.entries.iter().copied());
        let opts = AffectedOptions::default();
        let report = e.affected(cs, &entries, &opts);
        let selected = NodeSet::from_iter_in(
            self.g.node_count(),
            report.with_verdict(Verdict::Affected).map(|r| r.entry),
        );
        e.audit(
            cs,
            &entries,
            &selected,
            &opts,
            &AuditOptions {
                top,
                package_deps: self.deps.as_deref(),
                package_ecosystems: None,
                chains: true,
                ..AuditOptions::default()
            },
        )
    }

    fn signals(&self, r: &AuditReport, entry: &str) -> Vec<&'static str> {
        let v = r
            .verdicts
            .iter()
            .find(|v| self.g.path(v.entry) == entry)
            .unwrap_or_else(|| panic!("no verdict for {entry}"));
        Signal::of_mask(v.signals).map(Signal::as_str).collect()
    }
}

fn modified(paths: &[&str]) -> ChangeSet {
    let mut cs = ChangeSet::new();
    for p in paths {
        cs.push(ChangeKind::Modified, *p);
    }
    cs
}

fn source<'a>(r: &'a AuditReport, id: &str) -> &'a AuditSource {
    r.sources
        .iter()
        .find(|s| s.id == id)
        .unwrap_or_else(|| panic!("no source {id} in {:?}", ids(r)))
}

fn ids(r: &AuditReport) -> Vec<&str> {
    r.sources.iter().map(|s| s.id.as_str()).collect()
}

fn task(b: &mut GraphBuilder, pkg: PackageId, id: &str) -> NodeId {
    b.add_file(id, pkg, Some(TASK_LANG), false)
}

fn hub(b: &mut GraphBuilder, pkg: PackageId, id: &str, members: &[NodeId]) -> NodeId {
    let h = b.add_file(id, pkg, Some(HUB_LANG), false);
    for &m in members {
        b.edge(h, m, RefKind::FsRead);
    }
    h
}

fn generated_by(b: &mut GraphBuilder, file: NodeId, task: NodeId) {
    b.add_edge(
        file,
        EdgeSpec::new(Some(task), RefKind::Import).specifier("generated by task"),
    );
}

/// ```text
/// app/a.test.ts → app/a.ts → lib/util.ts              (plain)
/// app/b.test.ts → app/dist.ts → task:lib#build → members:lib/** → lib/util.ts, lib/other.ts
/// app/c.test.ts → app/dist.ts
/// ```
fn hub_graph() -> Fx {
    let mut b = MemGraph::builder();
    let root = b.package(".", None, "");
    let ta = b.add_file("app/a.test.ts", root, Some("js"), false);
    let tb = b.add_file("app/b.test.ts", root, Some("js"), false);
    let tc = b.add_file("app/c.test.ts", root, Some("js"), false);
    let a = b.add_file("app/a.ts", root, Some("js"), false);
    let dist = b.add_file("app/dist.ts", root, Some("js"), false);
    let util = b.add_file("lib/util.ts", root, Some("js"), false);
    let other = b.add_file("lib/other.ts", root, Some("js"), false);
    let h = hub(&mut b, root, "members:lib/**", &[util, other]);
    let t = task(&mut b, root, "task:lib#build");
    b.edge(t, h, RefKind::FsRead);
    generated_by(&mut b, dist, t);
    b.edge(ta, a, RefKind::Import)
        .edge(a, util, RefKind::Import)
        .edge(tb, dist, RefKind::Import)
        .edge(tc, dist, RefKind::Import);
    Fx {
        g: b.build().unwrap(),
        entries: vec![ta, tb, tc],
        deps: None,
    }
}

#[test]
fn a_plain_import_path_has_no_signal() {
    let fx = hub_graph();
    let r = fx.run(&modified(&["lib/util.ts"]));
    assert_eq!((r.entries, r.selected, r.implausible), (3, 3, 2));
    assert!(fx.signals(&r, "app/a.test.ts").is_empty());
    assert_eq!(fx.signals(&r, "app/b.test.ts"), ["non_import"]);
    assert_eq!((r.floor_only, r.change_only, r.floor_and_change), (0, 3, 0));
    let v = r
        .verdicts
        .iter()
        .find(|v| fx.g.path(v.entry) == "app/a.test.ts")
        .unwrap();
    assert_eq!(
        v.chain,
        [
            "modified lib/util.ts",
            "lib/util.ts",
            "app/a.ts",
            "app/a.test.ts"
        ]
    );
    assert_eq!(v.bridge, None);
}

#[test]
fn a_task_hub_is_the_source_of_what_only_it_selects() {
    let fx = hub_graph();
    let r = fx.run(&modified(&["lib/other.ts"]));
    // Only the hub path reaches the tests of app/dist.ts; a.test.ts is not
    // selected.
    assert_eq!((r.selected, r.implausible), (2, 2));
    // Hub and task both dominate the two tests: the one closest to the entries is
    // picked.
    let s = &r.sources[0];
    assert_eq!(
        (s.id.as_str(), s.kind),
        ("task:lib#build", SourceKind::Task)
    );
    assert_eq!((s.rank, s.freed, s.left), (Some(1), Some(2), Some(0)));
    assert_eq!((s.exclusive, s.inclusive), (2, 2));
    assert_eq!(s.signals.get("non_import"), Some(&2));
    assert_eq!(
        s.example,
        [
            "modified lib/other.ts",
            "lib/other.ts",
            "members:lib/**",
            "task:lib#build",
            "app/dist.ts",
            "app/b.test.ts"
        ]
    );
    assert_eq!(
        (s.changes.as_slice(), s.changes_total),
        (&["lib/other.ts".to_owned()][..], 1)
    );
    // The hub is reported too, with the same exclusive count, but it was not
    // needed.
    let h = source(&r, "members:lib/**");
    assert_eq!((h.exclusive, h.inclusive, h.rank), (2, 2, None));
    assert_eq!(r.left, 0);
    // Per kind, all sources of the kind together.
    let kinds: Vec<(SourceKind, usize, usize, usize)> = r
        .kinds
        .iter()
        .map(|k| (k.kind, k.sources, k.exclusive, k.inclusive))
        .collect();
    assert_eq!(
        kinds,
        [(SourceKind::Task, 1, 2, 2), (SourceKind::Members, 1, 2, 2)]
    );
    // The verdict names the first bridge on the witness chain and the pick.
    let v = r
        .verdicts
        .iter()
        .find(|v| fx.g.path(v.entry) == "app/b.test.ts")
        .unwrap();
    assert_eq!(
        v.bridge,
        Some((SourceKind::Members, "members:lib/**".to_owned()))
    );
    assert_eq!(v.source, Some(0));
    let json = r.to_value(&fx.g, VerdictFilter::Flagged);
    assert_eq!(json["entries"].as_array().unwrap().len(), 2);
    assert_eq!(json["entries"][0]["source"], "task:lib#build");
    assert_eq!(json["entries"][0]["plausible"], false);
    assert_eq!(json["sources"][0]["exclusive"], 2);
}

/// Two tasks generate the same file: neither is exclusive, the greedy order
/// needs both.
#[test]
fn redundant_sources_are_exclusive_only_together() {
    let mut b = MemGraph::builder();
    let root = b.package(".", None, "");
    let t1 = b.add_file("app/1.test.ts", root, Some("js"), false);
    let t2 = b.add_file("app/2.test.ts", root, Some("js"), false);
    let dist = b.add_file("app/dist.ts", root, Some("js"), false);
    let src = b.add_file("lib/src.ts", root, Some("js"), false);
    let a = task(&mut b, root, "task:lib#build");
    let c = task(&mut b, root, "task:lib#codegen");
    b.edge(a, src, RefKind::Import)
        .edge(c, src, RefKind::Import);
    generated_by(&mut b, dist, a);
    generated_by(&mut b, dist, c);
    b.edge(t1, dist, RefKind::Import)
        .edge(t2, dist, RefKind::Import);
    let fx = Fx {
        g: b.build().unwrap(),
        entries: vec![t1, t2],
        deps: None,
    };
    let r = fx.run(&modified(&["lib/src.ts"]));
    assert_eq!((r.selected, r.implausible, r.left), (2, 2, 0));
    assert_eq!(ids(&r), ["task:lib#build", "task:lib#codegen"]);
    let (first, second) = (&r.sources[0], &r.sources[1]);
    assert_eq!(
        (first.exclusive, first.inclusive, first.freed),
        (0, 2, Some(0))
    );
    assert_eq!(
        (second.exclusive, second.inclusive, second.freed),
        (0, 2, Some(2))
    );
    assert_eq!((first.left, second.left), (Some(2), Some(0)));
    // With one pick, the entries stay selected.
    let r = fx.run_top(&modified(&["lib/src.ts"]), 1);
    assert_eq!(r.left, 2);
}

/// ```text
/// t/floor.test.ts → src/dyn.ts (open computed_specifier)
/// t/both.test.ts  → src/dyn.ts, src/a.ts
/// t/plain.test.ts → src/a.ts
/// ```
#[test]
fn floor_only_change_only_and_both() {
    let mut b = MemGraph::builder();
    let tf = b.file("t/floor.test.ts");
    let tb = b.file("t/both.test.ts");
    let tp = b.file("t/plain.test.ts");
    let d = b.file("src/dyn.ts");
    let a = b.file("src/a.ts");
    b.edge(tf, d, RefKind::Import)
        .edge(tb, d, RefKind::Import)
        .edge(tb, a, RefKind::Import)
        .edge(tp, a, RefKind::Import);
    b.uncertainty(d, UncertaintyKind::ComputedSpecifier, 3, "require(x)");
    let fx = Fx {
        g: b.build().unwrap(),
        entries: vec![tf, tb, tp],
        deps: None,
    };
    let r = fx.run(&modified(&["src/a.ts"]));
    assert_eq!(r.selected, 3);
    assert_eq!((r.floor_only, r.change_only, r.floor_and_change), (1, 1, 1));
    assert_eq!(fx.signals(&r, "t/floor.test.ts"), ["non_import", "floor"]);
    assert!(fx.signals(&r, "t/both.test.ts").is_empty());
    assert_eq!(r.implausible, 1);
    // The floor and its only site dominate the same entry: the site is the source.
    let s = &r.sources[0];
    assert_eq!(
        (s.id.as_str(), s.kind),
        ("uncertain:src/dyn.ts", SourceKind::Uncertain)
    );
    assert_eq!((s.exclusive, s.inclusive, s.freed), (1, 1, Some(1)));
    assert_eq!(
        s.example,
        [
            "floor",
            "[open uncertainty]",
            "src/dyn.ts",
            "t/floor.test.ts"
        ]
    );
    assert_eq!(source(&r, "floor").exclusive, 1);
    // An unrelated change: everything selected is the floor.
    let r = fx.run(&modified(&["README.md"]));
    assert_eq!((r.selected, r.floor_only, r.implausible), (2, 2, 2));
}

/// The floor does not cross a data edge (a task that only reads a hub's
/// members), as in the selection itself: a test selected through such a task by
/// a change is not also credited to the floor, and an uncertain member is not a
/// source of it.
///
/// ```text
/// t/x.test.ts → app/dist.ts → task:lib#check ⇢(data) members:lib/** → lib/dyn.ts (open), lib/a.ts
/// t/y.test.ts → lib/dyn.ts
/// ```
#[test]
fn the_floor_does_not_cross_data_edges() {
    let mut b = MemGraph::builder();
    let root = b.package(".", None, "");
    let tx = b.add_file("t/x.test.ts", root, Some("js"), false);
    let ty = b.add_file("t/y.test.ts", root, Some("js"), false);
    let dist = b.add_file("app/dist.ts", root, Some("js"), false);
    let dynamic = b.add_file("lib/dyn.ts", root, Some("js"), false);
    let a = b.add_file("lib/a.ts", root, Some("js"), false);
    let h = hub(&mut b, root, "members:lib/**", &[dynamic, a]);
    let t = task(&mut b, root, "task:lib#check");
    b.add_edge(
        t,
        EdgeSpec::new(Some(h), RefKind::FsRead).flags(RefFlags::DATA),
    );
    generated_by(&mut b, dist, t);
    b.edge(tx, dist, RefKind::Import)
        .edge(ty, dynamic, RefKind::Import);
    b.uncertainty(dynamic, UncertaintyKind::ComputedSpecifier, 3, "require(x)");
    let fx = Fx {
        g: b.build().unwrap(),
        entries: vec![tx, ty],
        deps: None,
    };
    // No change reaches the hub: only the test that runs the uncertain file is
    // selected.
    let r = fx.run(&modified(&["README.md"]));
    assert_eq!((r.selected, r.floor_only), (1, 1));
    assert_eq!(source(&r, "uncertain:lib/dyn.ts").inclusive, 1);
    // A change of another member: the task's consumer is selected by the change
    // alone.
    let r = fx.run(&modified(&["lib/a.ts"]));
    assert_eq!(r.selected, 2);
    assert_eq!((r.floor_only, r.change_only, r.floor_and_change), (1, 1, 0));
    assert_eq!(fx.signals(&r, "t/x.test.ts"), ["non_import"]);
}

/// The floor and a task hub reach the same test: removing either alone frees
/// nothing, so both have exclusive 0. Without the floor (`--on-uncertain
/// ignore`) the hub is exclusive.
///
/// ```text
/// t/x.test.ts → src/dyn.ts (open uncertainty)
/// t/x.test.ts → app/dist.ts → task:lib#build → lib/src.ts
/// ```
#[test]
fn a_source_the_floor_also_covers_is_exclusive_without_the_floor() {
    let mut b = MemGraph::builder();
    let root = b.package(".", None, "");
    let t = b.add_file("t/x.test.ts", root, Some("js"), false);
    let d = b.add_file("src/dyn.ts", root, Some("js"), false);
    let dist = b.add_file("app/dist.ts", root, Some("js"), false);
    let src = b.add_file("lib/src.ts", root, Some("js"), false);
    let build = task(&mut b, root, "task:lib#build");
    b.edge(build, src, RefKind::Import);
    generated_by(&mut b, dist, build);
    b.edge(t, d, RefKind::Import).edge(t, dist, RefKind::Import);
    b.uncertainty(d, UncertaintyKind::ComputedSpecifier, 3, "require(x)");
    let fx = Fx {
        g: b.build().unwrap(),
        entries: vec![t],
        deps: None,
    };
    let r = fx.run(&modified(&["lib/src.ts"]));
    assert_eq!((r.floor_only, r.change_only, r.floor_and_change), (0, 0, 1));
    assert_eq!(fx.signals(&r, "t/x.test.ts"), ["non_import"]);
    let hub = source(&r, "task:lib#build");
    assert_eq!(
        (hub.exclusive, hub.exclusive_no_floor, hub.inclusive),
        (0, 1, 1)
    );
    // Its example starts at the change, not at the floor.
    assert_eq!(
        hub.example,
        [
            "modified lib/src.ts",
            "lib/src.ts",
            "task:lib#build",
            "app/dist.ts",
            "t/x.test.ts"
        ]
    );
    let floor = source(&r, "floor");
    assert_eq!(
        (floor.exclusive, floor.exclusive_no_floor, floor.inclusive),
        (0, 0, 1)
    );
    // The greedy order needs two picks: the first frees nothing, the second the
    // test.
    let freed: Vec<Option<usize>> = r.sources.iter().take(2).map(|s| s.freed).collect();
    assert_eq!(freed, [Some(0), Some(1)]);
    assert_eq!(r.left, 0);
    // The entry's chain is the change's.
    assert_eq!(r.verdicts[0].chain[0], "modified lib/src.ts");
}

/// ```text
/// packages: root, web (js), svc (go, depends on nothing), lib (js; web depends on lib)
/// svc/x_test.go  → svc/x.go → task:svc#gen → members:** → every file
/// svc/y_test.go  → svc/y.go --embed--> web/tmpl.ts
/// web/w.test.ts  → web/w.ts → lib/l.ts
/// ```
fn eco_graph() -> Fx {
    let mut b = MemGraph::builder();
    let root = b.package(".", None, "");
    let web = b.package("web", None, "web");
    let svc = b.package("go:example.com/svc", None, "svc");
    let lib = b.package("lib", None, "lib");
    let xt = b.add_file("svc/x_test.go", svc, Some("go"), false);
    let x = b.add_file("svc/x.go", svc, Some("go"), false);
    let yt = b.add_file("svc/y_test.go", svc, Some("go"), false);
    let y = b.add_file("svc/y.go", svc, Some("go"), false);
    let wt = b.add_file("web/w.test.ts", web, Some("js"), false);
    let w = b.add_file("web/w.ts", web, Some("js"), false);
    let tmpl = b.add_file("web/tmpl.ts", web, Some("js"), false);
    let l = b.add_file("lib/l.ts", lib, Some("js"), false);
    let data = b.add_file("svc/data.json", svc, None, false);
    let h = hub(&mut b, root, "members:**", &[w, tmpl, l, data, x, y]);
    let t = task(&mut b, svc, "task:svc#gen");
    b.edge(t, h, RefKind::FsRead);
    generated_by(&mut b, x, t);
    b.edge(xt, x, RefKind::Import)
        .edge(yt, y, RefKind::Import)
        .edge(y, tmpl, RefKind::Embed)
        .edge(wt, w, RefKind::Import)
        .edge(w, l, RefKind::Import);
    let mut deps = vec![Vec::new(); 4];
    deps[web.0 as usize] = vec![lib];
    Fx {
        g: b.build().unwrap(),
        entries: vec![xt, yt, wt],
        deps: Some(deps),
    }
}

#[test]
fn a_typescript_change_selecting_a_go_test_is_cross_ecosystem() {
    let fx = eco_graph();
    let r = fx.run(&modified(&["lib/l.ts"]));
    assert_eq!(r.selected, 2);
    assert_eq!(
        fx.signals(&r, "svc/x_test.go"),
        ["non_import", "cross_ecosystem", "no_package_dep"]
    );
    // web depends on lib: a plain, declared, same-ecosystem path.
    assert!(fx.signals(&r, "web/w.test.ts").is_empty());
    let s = &r.sources[0];
    assert_eq!(s.id, "task:svc#gen");
    assert_eq!(s.signals.get("cross_ecosystem"), Some(&1));
    // The a-priori relation is there for unselected entries too (y_test.go).
    let json = r.to_value(&fx.g, VerdictFilter::All);
    let y = json["entries"]
        .as_array()
        .unwrap()
        .iter()
        .find(|e| e["entry"] == "svc/y_test.go")
        .unwrap();
    assert_eq!(y["selected"], false);
    assert_eq!(y["a_priori"]["cross_ecosystem"], true);
    assert_eq!(y["a_priori"]["no_package_dep"], true);
    assert_eq!(y["ecosystem"], "go");
}

#[test]
fn neutral_files_and_known_bridges_are_not_cross_ecosystem() {
    let fx = eco_graph();
    // A data file in the Go package: neutral ecosystem, same package.
    let r = fx.run(&modified(&["svc/data.json"]));
    assert_eq!(fx.signals(&r, "svc/x_test.go"), ["non_import"]);
    // A TypeScript file that Go code embeds: an explicit reference to that very
    // file is a known bridge, so the ecosystem signal stays off; the package
    // signal fires (svc does not declare web) and the embed is the source.
    let r = fx.run(&modified(&["web/tmpl.ts"]));
    assert_eq!(
        fx.signals(&r, "svc/y_test.go"),
        ["non_import", "no_package_dep"]
    );
    assert_eq!(
        fx.signals(&r, "svc/x_test.go"),
        ["non_import", "cross_ecosystem", "no_package_dep"]
    );
    let s = source(&r, "read-by:svc/y.go");
    assert_eq!((s.kind, s.exclusive), (SourceKind::Read, 1));
    assert_eq!(
        s.example,
        [
            "modified web/tmpl.ts",
            "web/tmpl.ts",
            "[reads source]",
            "svc/y.go",
            "svc/y_test.go"
        ]
    );
}

/// ```text
/// packages a, b (depends on a), c (declares nothing)
/// b/b.test.ts → a/x.ts            declared
/// c/c.test.ts → c/c.ts → a/x.ts   undeclared: a relative import across the boundary
/// ```
#[test]
fn an_import_without_a_declared_dependency_is_flagged() {
    let mut b = MemGraph::builder();
    b.package(".", None, "");
    let pa = b.package("a", None, "a");
    let pb = b.package("b", None, "b");
    let pc = b.package("c", None, "c");
    let x = b.add_file("a/x.ts", pa, Some("js"), false);
    let bt = b.add_file("b/b.test.ts", pb, Some("js"), false);
    let ct = b.add_file("c/c.test.ts", pc, Some("js"), false);
    let c = b.add_file("c/c.ts", pc, Some("js"), false);
    b.edge(bt, x, RefKind::Import)
        .edge(ct, c, RefKind::Import)
        .edge(c, x, RefKind::Import);
    let mut deps = vec![Vec::new(); 4];
    deps[pb.0 as usize] = vec![pa];
    let fx = Fx {
        g: b.build().unwrap(),
        entries: vec![bt, ct],
        deps: Some(deps),
    };
    let r = fx.run(&modified(&["a/x.ts"]));
    assert!(fx.signals(&r, "b/b.test.ts").is_empty());
    assert_eq!(
        fx.signals(&r, "c/c.test.ts"),
        ["non_import", "no_package_dep"]
    );
    let s = &r.sources[0];
    assert_eq!(
        (s.id.as_str(), s.kind),
        ("undeclared:c -> a", SourceKind::Undeclared)
    );
    assert_eq!((s.exclusive, s.freed), (1, Some(1)));
    // Without the dependency table the signal and the bridge are off.
    let fx = Fx { deps: None, ..fx };
    let r = fx.run(&modified(&["a/x.ts"]));
    assert_eq!(r.implausible, 0);
}

/// ```text
/// svc/.vercel.approvers ∈ members:svc/** ← task:svc#build ← svc/gen.ts ← svc/s.test.ts
/// .github/ci.test.ts reads .github/workflows/ci.yml
/// ```
#[test]
fn steering_files_select_only_through_explicit_references() {
    let mut b = MemGraph::builder();
    let root = b.package(".", None, "");
    let st = b.add_file("svc/s.test.ts", root, Some("js"), false);
    let genf = b.add_file("svc/gen.ts", root, Some("js"), false);
    let appr = b.add_file("svc/.vercel.approvers", root, None, false);
    let src = b.add_file("svc/src.ts", root, Some("js"), false);
    let ct = b.add_file(".github/ci.test.ts", root, Some("js"), false);
    let yml = b.add_file(".github/workflows/ci.yml", root, None, false);
    let h = hub(&mut b, root, "members:svc/**", &[appr, src]);
    let t = task(&mut b, root, "task:svc#build");
    b.edge(t, h, RefKind::FsRead);
    generated_by(&mut b, genf, t);
    b.edge(st, genf, RefKind::Import)
        .edge(ct, yml, RefKind::FsRead);
    let fx = Fx {
        g: b.build().unwrap(),
        entries: vec![st, ct],
        deps: None,
    };
    let r = fx.run(&modified(&[
        "svc/.vercel.approvers",
        ".github/workflows/ci.yml",
    ]));
    assert_eq!(r.selected, 2);
    // The CI test reads the workflow file: an explicit reference, plausible.
    assert!(fx.signals(&r, ".github/ci.test.ts").is_empty());
    assert_eq!(fx.signals(&r, "svc/s.test.ts"), ["non_import", "steering"]);
    assert_eq!(
        (
            r.steering.changes,
            r.steering.inclusive,
            r.steering.exclusive
        ),
        (2, 1, 1)
    );
    assert_eq!(r.steering.classes.get(".vercel.approvers"), Some(&1));
    assert_eq!(r.steering.classes.get(".github/**"), Some(&1));
    let s = source(&r, "steering:.vercel.approvers");
    assert_eq!(
        (s.kind, s.exclusive, s.inclusive),
        (SourceKind::Steering, 1, 1)
    );
    // With a source change in the same hub, steering is no longer the only reason.
    let r = fx.run(&modified(&["svc/.vercel.approvers", "svc/src.ts"]));
    assert_eq!(fx.signals(&r, "svc/s.test.ts"), ["non_import"]);
    assert_eq!((r.steering.inclusive, r.steering.exclusive), (1, 0));
    assert_eq!(source(&r, "steering:.vercel.approvers").exclusive, 0);
    let v = &r
        .verdicts
        .iter()
        .find(|v| fx.g.path(v.entry) == "svc/s.test.ts")
        .unwrap();
    assert_eq!(v.a_priori & Signal::Steering.bit(), 0);
}

/// ```text
/// t/a.test.ts → jest:setup_file setup.ts → src/big.ts
/// t/b.test.ts → jest:setup_file setup.ts;  t/b.test.ts → (type-only) src/types.ts
/// t/c.test.ts → t/b.test.ts (a test importing a test)
/// ```
#[test]
fn framework_type_only_and_via_test_bridges() {
    let mut b = MemGraph::builder();
    let ta = b.file("t/a.test.ts");
    let tb = b.file("t/b.test.ts");
    let tc = b.file("t/c.test.ts");
    let setup = b.file("setup.ts");
    let big = b.file("src/big.ts");
    let types = b.file("src/types.ts");
    let helper = b.file("src/helper.ts");
    for t in [ta, tb] {
        b.add_edge(
            t,
            EdgeSpec::new(Some(setup), RefKind::Require).specifier("jest:setup_file setup.ts"),
        );
    }
    b.edge(setup, big, RefKind::Import);
    b.add_edge(
        tb,
        EdgeSpec::new(Some(types), RefKind::Import).flags(RefFlags::TYPE_ONLY),
    );
    b.edge(tb, helper, RefKind::Import)
        .edge(tc, tb, RefKind::Import);
    let fx = Fx {
        g: b.build().unwrap(),
        entries: vec![ta, tb, tc],
        deps: None,
    };
    let r = fx.run(&modified(&["src/big.ts"]));
    assert_eq!(r.selected, 3);
    assert_eq!(fx.signals(&r, "t/a.test.ts"), ["non_import"]);
    assert_eq!(fx.signals(&r, "t/c.test.ts"), ["non_import", "via_test"]);
    let s = &r.sources[0];
    assert_eq!(
        (s.id.as_str(), s.kind),
        ("jest:setup_file setup.ts", SourceKind::Framework)
    );
    assert_eq!((s.exclusive, s.freed), (3, Some(3)));
    assert_eq!(source(&r, "via-test:t/b.test.ts").exclusive, 1);

    let r = fx.run(&modified(&["src/types.ts"]));
    assert_eq!(r.selected, 2);
    assert_eq!(fx.signals(&r, "t/b.test.ts"), ["non_import", "type_only"]);
    assert_eq!(
        fx.signals(&r, "t/c.test.ts"),
        ["non_import", "type_only", "via_test"]
    );
    assert_eq!(r.sources[0].id, "type-only:src/types.ts");
    assert_eq!(r.sources[0].exclusive, 2);

    // A plain change in a helper: b is plausible, c only reaches it through b.
    let r = fx.run(&modified(&["src/helper.ts"]));
    assert!(fx.signals(&r, "t/b.test.ts").is_empty());
    assert_eq!(fx.signals(&r, "t/c.test.ts"), ["non_import", "via_test"]);
    let mut out = Vec::new();
    r.write_text(&mut out).unwrap();
    let text = String::from_utf8(out).unwrap();
    assert!(text.contains("audit: 2 of 3 entries selected"), "{text}");
    assert!(text.contains("via-test:t/b.test.ts"), "{text}");
}

/// `affected` evaluates transpile-only tests without type-only edges and other
/// entries with every edge: the audit runs once per pass with the pass's
/// filter, and the reports merge.
///
/// ```text
/// t/iso.test.ts   → (type-only) src/types.ts;  t/iso.test.ts   → app/dist.ts → task:lib#build → lib/src.ts
/// t/check.test.ts → (type-only) src/types.ts;  t/check.test.ts → app/dist.ts
/// ```
#[test]
fn passes_with_their_own_edge_filter_merge() {
    let mut b = MemGraph::builder();
    let root = b.package(".", None, "");
    let iso = b.add_file("t/iso.test.ts", root, Some("js"), false);
    let check = b.add_file("t/check.test.ts", root, Some("js"), false);
    let types = b.add_file("src/types.ts", root, Some("js"), false);
    let dist = b.add_file("app/dist.ts", root, Some("js"), false);
    let src = b.add_file("lib/src.ts", root, Some("js"), false);
    let build = task(&mut b, root, "task:lib#build");
    b.edge(build, src, RefKind::Import);
    generated_by(&mut b, dist, build);
    for t in [iso, check] {
        b.add_edge(
            t,
            EdgeSpec::new(Some(types), RefKind::Import).flags(RefFlags::TYPE_ONLY),
        );
        b.edge(t, dist, RefKind::Import);
    }
    let g = b.build().unwrap();
    let e = Engine::new(&g);
    let n = g.node_count();
    let opts = AffectedOptions::default();
    let no_types = EdgeFilter::ALL.without_flags(RefFlags::TYPE_ONLY);
    let pass = |cs: &ChangeSet, entry: NodeId, filter: Option<EdgeFilter>, selected: &[NodeId]| {
        e.audit(
            cs,
            &NodeSet::from_iter_in(n, [entry]),
            &NodeSet::from_iter_in(n, selected.iter().copied()),
            &opts,
            &AuditOptions {
                filter,
                ignored_steering: &[".github/CODEOWNERS".to_owned()],
                ..AuditOptions::default()
            },
        )
    };
    // A type change: only the type-checking test is selected, through the type-only
    // edge.
    let cs = modified(&["src/types.ts"]);
    let a = pass(&cs, iso, Some(no_types), &[check]);
    assert_eq!((a.entries, a.selected, a.implausible), (1, 0, 0));
    let b2 = pass(&cs, check, None, &[check]);
    assert_eq!(b2.sources[0].id, "type-only:src/types.ts");
    let m = a.merge(b2);
    assert_eq!((m.entries, m.selected, m.implausible, m.left), (2, 1, 1, 0));
    assert_eq!(m.signal_counts["type_only"], 1);
    assert_eq!(m.sources[0].id, "type-only:src/types.ts");
    assert_eq!((m.sources[0].rank, m.sources[0].left), (Some(1), Some(0)));
    // Ignored steering files are counted, once, and reach nothing.
    assert_eq!(
        (m.steering.changes, m.steering.ignored, m.steering.inclusive),
        (1, 1, 0)
    );
    assert_eq!(m.changes, 2);
    // A source change: both tests through the task; the counts of the passes add
    // up.
    let cs = modified(&["lib/src.ts"]);
    let m =
        pass(&cs, iso, Some(no_types), &[iso, check]).merge(pass(&cs, check, None, &[iso, check]));
    assert_eq!((m.selected, m.implausible), (2, 2));
    let t = source(&m, "task:lib#build");
    assert_eq!(
        (t.exclusive, t.inclusive, t.freed, t.rank),
        (2, 2, Some(2), Some(1))
    );
    let k = m.kinds.iter().find(|k| k.kind == SourceKind::Task).unwrap();
    assert_eq!((k.exclusive, k.inclusive), (2, 2));
    let paths: Vec<&str> = m.verdicts.iter().map(|v| g.path(v.entry)).collect();
    assert_eq!(paths, ["t/iso.test.ts", "t/check.test.ts"]);
    assert!(m.verdicts.iter().all(|v| v.source == Some(0)));
}

/// An added file that matches a probe and a directory listing.
#[test]
fn probes_and_listings_are_sources() {
    let mut b = MemGraph::builder();
    let t1 = b.file("t/1.test.ts");
    let t2 = b.file("t/2.test.ts");
    let a = b.file("src/a.ts");
    let l = b.file("src/list.ts");
    b.edge(t1, a, RefKind::Import).edge(t2, l, RefKind::Import);
    b.probe(a, "src/new.ts");
    b.membership(l, "src", "*.ts");
    let fx = Fx {
        g: b.build().unwrap(),
        entries: vec![t1, t2],
        deps: None,
    };
    let mut cs = ChangeSet::new();
    cs.push(ChangeKind::Added, "src/new.ts");
    let r = fx.run(&cs);
    assert_eq!((r.selected, r.implausible), (2, 2));
    assert_eq!(source(&r, "probe:src/new.ts").exclusive, 1);
    let s = source(&r, "listing:src/*.ts");
    assert_eq!((s.kind, s.exclusive), (SourceKind::Listing, 1));
    assert_eq!(
        s.example,
        [
            "added src/new.ts",
            "[listing src/*.ts]",
            "src/list.ts",
            "t/2.test.ts"
        ]
    );
}

/// Exclusive counts equal a brute-force removal on pseudo-random graphs, and
/// the greedy counts add up.
#[test]
fn exclusive_counts_match_brute_force() {
    let mut total_checked = 0;
    for seed in 1..8u64 {
        let mut x = seed;
        let mut rnd = move |m: u32| {
            x = x
                .wrapping_mul(6364136223846793005)
                .wrapping_add(1442695040888963407);
            ((x >> 33) % m as u64) as u32
        };
        let n = 120u32;
        let mut b = MemGraph::builder();
        let root = b.package(".", None, "");
        let nodes: Vec<NodeId> = (0..n)
            .map(|i| {
                if i % 2 == 1 {
                    b.add_file(&format!("task:t{i:03}"), root, Some(TASK_LANG), false)
                } else {
                    b.add_file(&format!("f{i:03}.ts"), root, Some("js"), false)
                }
            })
            .collect();
        for _ in 0..3 * n {
            let (from, to) = (rnd(n), rnd(n));
            if to > from || rnd(8) == 0 {
                b.edge(nodes[from as usize], nodes[to as usize], RefKind::Import);
            }
        }
        let g = b.build().unwrap();
        let entries: Vec<NodeId> = nodes.iter().copied().filter(|n| n.0 % 10 == 0).collect();
        let fx = Fx {
            g,
            entries,
            deps: None,
        };
        let cs = modified(&["f118.ts", "f116.ts", "f114.ts"]);
        let r = fx.run_top(&cs, 1000);
        // Brute force: remove one task node, recompute the selection.
        let e = Engine::new(&fx.g);
        let entry_set = NodeSet::from_iter_in(n, fx.entries.iter().copied());
        let seeds = NodeSet::from_iter_in(
            n,
            ["f114.ts", "f116.ts", "f118.ts"]
                .iter()
                .filter_map(|p| fx.g.node_by_path(p)),
        );
        let reach_without = |skip: Option<NodeId>| -> Vec<NodeId> {
            // Reverse search by hand, skipping one node.
            let mut seen = vec![false; n as usize];
            let mut q: Vec<NodeId> = seeds.iter().filter(|s| Some(*s) != skip).collect();
            for s in &q {
                seen[s.index()] = true;
            }
            let rev = e.reverse();
            let mut head = 0;
            while head < q.len() {
                let u = q[head];
                head += 1;
                for &v in rev.neighbors(u).0 {
                    if !seen[v as usize] && Some(NodeId(v)) != skip {
                        seen[v as usize] = true;
                        q.push(NodeId(v));
                    }
                }
            }
            q.into_iter().filter(|x| entry_set.contains(*x)).collect()
        };
        let base = reach_without(None);
        assert_eq!(r.selected, base.len(), "seed {seed}");
        let implausible: Vec<NodeId> = r
            .verdicts
            .iter()
            .filter(|v| v.signals != 0)
            .map(|v| v.entry)
            .collect();
        let mut checked = 0;
        for s in r.sources.iter().filter(|s| s.kind == SourceKind::Task) {
            let node = fx.g.node_by_path(&s.id).unwrap();
            let left = reach_without(Some(node));
            let dropped = implausible.iter().filter(|x| !left.contains(x)).count();
            assert_eq!(s.exclusive, dropped, "seed {seed}, {}", s.id);
            checked += 1;
        }
        total_checked += checked;
        // Every bridge can be picked, so the picks free everything.
        let freed: usize = r.sources.iter().filter_map(|s| s.freed).sum();
        assert_eq!(freed + r.left, r.implausible, "seed {seed}");
        assert_eq!(r.left, 0, "seed {seed}");
    }
    assert!(total_checked >= 20, "{total_checked} task sources checked");
}
